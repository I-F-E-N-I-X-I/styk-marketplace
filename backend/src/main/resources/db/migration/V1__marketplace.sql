CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(160) NOT NULL UNIQUE, name VARCHAR(100) NOT NULL,
 password VARCHAR(100) NOT NULL, role VARCHAR(20) NOT NULL,
 enabled BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 seller_id BIGINT NOT NULL REFERENCES users(id), name VARCHAR(160) NOT NULL,
 brand VARCHAR(100) NOT NULL, category VARCHAR(60) NOT NULL, description VARCHAR(4000) NOT NULL,
 price NUMERIC(12,2) NOT NULL CHECK (price > 0), old_price NUMERIC(12,2),
 image VARCHAR(500) NOT NULL, color VARCHAR(30) NOT NULL, sku VARCHAR(80) NOT NULL UNIQUE,
 status VARCHAR(20) NOT NULL, stock INTEGER NOT NULL CHECK (stock >= 0),
 reserved INTEGER NOT NULL DEFAULT 0 CHECK (reserved >= 0 AND reserved <= stock),
 threshold INTEGER NOT NULL DEFAULT 10 CHECK (threshold >= 0),
 target INTEGER NOT NULL DEFAULT 40 CHECK (target >= threshold), location VARCHAR(30) NOT NULL
);
CREATE INDEX products_catalog_idx ON products(status, category);
CREATE INDEX products_seller_idx ON products(seller_id);
CREATE TABLE cart_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 product_id BIGINT NOT NULL REFERENCES products(id), quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 99),
 UNIQUE(user_id, product_id)
);
CREATE TABLE orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 status VARCHAR(30) NOT NULL, payment_status VARCHAR(30) NOT NULL, address VARCHAR(400) NOT NULL,
 delivery VARCHAR(30) NOT NULL, total NUMERIC(12,2) NOT NULL, discount NUMERIC(12,2) NOT NULL,
 request_key VARCHAR(80) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(user_id, request_key)
);
CREATE INDEX orders_user_idx ON orders(user_id, created_at);
CREATE TABLE order_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL REFERENCES orders(id),
 product_id BIGINT NOT NULL REFERENCES products(id), name VARCHAR(160) NOT NULL,
 price NUMERIC(12,2) NOT NULL, quantity INTEGER NOT NULL, seller_id BIGINT NOT NULL REFERENCES users(id)
);
CREATE TABLE supply_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id BIGINT NOT NULL REFERENCES products(id),
 seller_id BIGINT NOT NULL REFERENCES users(id), quantity INTEGER NOT NULL CHECK (quantity > 0),
 received INTEGER NOT NULL DEFAULT 0, status VARCHAR(30) NOT NULL, note VARCHAR(500) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX supply_product_idx ON supply_requests(product_id, status);
CREATE TABLE stock_movements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id BIGINT NOT NULL REFERENCES products(id),
 type VARCHAR(30) NOT NULL, quantity INTEGER NOT NULL, reference VARCHAR(100) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE order_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL REFERENCES orders(id),
 status VARCHAR(30) NOT NULL, note VARCHAR(400) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE reviews (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 product_id BIGINT NOT NULL REFERENCES products(id), author VARCHAR(100) NOT NULL,
 rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5), text VARCHAR(2000) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, UNIQUE(user_id, product_id)
);
CREATE TABLE favorites (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 product_id BIGINT NOT NULL REFERENCES products(id), UNIQUE(user_id, product_id)
);
CREATE TABLE audit_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor VARCHAR(160) NOT NULL,
 action VARCHAR(400) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
